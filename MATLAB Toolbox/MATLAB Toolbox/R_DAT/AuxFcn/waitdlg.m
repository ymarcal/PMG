function varargout = waitdlg(Message,Title,CreateMode)
% Cria mensagem de "aguarde"

if nargin<3
    CreateMode = 'normal';
end
if nargin<2
    Title = '';
end
if ~nargin
    Message = 'Please wait while something happens.';
end

load waiticondata.mat;

bgc = get(0,'DefaultUicontrolBackgroundColor');

bg = find(IconMap(:,1)==1 & IconMap(:,2)==0 & IconMap(:,3)==1);
if length(bg) == 1
    IconMap(bg,:) = bgc;
end

ws = get(0,'ScreenSize');

[ext, hgt] = strextent(Message);
ext = max(ext)+10;

fw = max(200,10+51+10+ext+15);
fh = 30+hgt+30;


h = dialog(                                                  ...
    'Name'            , Title                              , ...
    'Position'        ,[.5*(ws(3)-fw) .5*(ws(4)-fh) fw fh] , ...
    'Pointer'         ,'watch'                             , ...
    'Units'           ,'pixels'                            , ...
    'Visible'         ,'on'                                , ...
    'WindowStyle'     , CreateMode                         , ...
    'HandleVisibility','callback'                          , ...
    'Toolbar'         ,'none'                              , ...
    'Color'           , bgc                                , ...
    'Colormap'        , IconMap                            );

th = uicontrol(h                         , ...
    'Style'              ,'text'         , ...
    'Units'              ,'pixels'       , ...
    'Position'           ,[71 30 ext hgt], ...
    'String'             , Message       , ...
    'HorizontalAlignment','left'         );


ah = axes(                           ...
    'Parent'  , h                   ,...
    'Units'   ,'pixels'             ,...
    'Position',[10 .5*(fh-51) 51 51],...
    'YDir'    ,'reverse'            ,...
    'XLim'    ,[.5 51.5]            ,...
    'YLim'    ,[.5 51.5]            ,...
    'Visible' ,'off'                );

ih = image(...
    'Parent',ah,...
    'CData',IconData);  

drawnow;

if nargout == 1
    varargout{1} = h;
end
